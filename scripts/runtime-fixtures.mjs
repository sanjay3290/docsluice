import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/** Authoritative source file for each embedded runtime fixture. */
export const fixtureSources = Object.freeze({
  validZip: 'corpus/zip/hello.odt',
  traversalZip: 'hostile/zip/path-traversal.zip',
  hostileXml: 'hostile/xml/xxe-file.xml',
  csv: 'corpus/csv/rfc4180-crlf.csv',
  html: 'corpus/html/blog-post.html',
  hostileHtml: 'hostile/html/script-and-handlers.html',
  pdf: 'corpus/pdf/labels-outline-links.pdf',
});
const outputRelative = 'packages/docsluice/test-runtime/fixtures.generated.mjs';

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

/** Produce an embedded web-standard fixture module and source hashes. */
export async function generateFixtureModule({ root = defaultRoot } = {}) {
  const values = [];
  for (const [name, relative] of Object.entries(fixtureSources).sort(([a], [b]) => compareText(a, b))) {
    const bytes = await readFile(path.join(root, relative));
    values.push({
      name,
      base64: bytes.toString('base64'),
      sha256: createHash('sha256').update(bytes).digest('hex'),
    });
  }
  const hashes = values.map(({ name, sha256 }) => `  ${name}: '${sha256}',`).join('\n');
  const encoded = values
    .map(({ name, base64 }) =>
      base64.length + name.length + 6 > 120 ? `  ${name}:\n    '${base64}',` : `  ${name}: '${base64}',`,
    )
    .join('\n');
  return `// Generated by scripts/runtime-fixtures.mjs; source corpus and hostile files remain authoritative.\nexport const runtimeFixtureSourceHashes = Object.freeze({\n${hashes}\n});\n\nconst encodedFixtures = Object.freeze({\n${encoded}\n});\n\nfunction decodeBase64(value) {\n  const binary = globalThis.atob(value);\n  const bytes = new Uint8Array(binary.length);\n  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index);\n  return bytes;\n}\n\nexport function loadRuntimeFixtures() {\n  return Object.freeze({\n${values.map(({ name }) => `    ${name}: decodeBase64(encodedFixtures.${name}),`).join('\n')}\n  });\n}\n`;
}

export async function checkFixtureModule({ root = defaultRoot } = {}) {
  const expected = await generateFixtureModule({ root });
  try {
    return (await readFile(path.join(root, outputRelative), 'utf8')) === expected;
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return false;
    throw error;
  }
}

async function main(argv) {
  let root = defaultRoot;
  let check = false;
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--check') check = true;
    else if (argv[index] === '--root' && argv[index + 1]) root = path.resolve(argv[++index]);
    else throw new Error(`Unknown argument: ${argv[index]}`);
  }
  const output = path.join(root, outputRelative);
  if (check) {
    if (!(await checkFixtureModule({ root }))) {
      process.stderr.write(
        'Embedded runtime fixtures are out of date; run node scripts/runtime-fixtures.mjs.\n',
      );
      return 1;
    }
    return 0;
  }
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, await generateFixtureModule({ root }));
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  try {
    process.exitCode = await main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
